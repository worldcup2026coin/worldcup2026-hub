export function getHostCityBySlug(slug: string) {
  return hostCities.find((city) => city.slug === slug);
}

export function getStadiumBySlug(slug: string) {
  return stadiums.find((stadium) => stadium.slug === slug);
}

export function getStadiumForCity(citySlug: string) {
  return stadiums.find((stadium) => stadium.citySlug === citySlug);
}

export function getHostCityForStadium(citySlug: string) {
  return hostCities.find((city) => city.slug === citySlug);
}
